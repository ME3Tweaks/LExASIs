#!/usr/bin/env python3
"""
One-off tool: extracts every public symbol from a set of Wwise v56-era (2010.3.3) SDK
static libs via `dumpbin /linkermember:1` and emits a single merged .def EXPORTS file.
Purpose: produce a DLL that pulls in as much of the real engine/plugin code as possible
(no actual calling code needed - a .def EXPORTS entry is itself a valid "root reference"
that pulls a symbol straight out of a linked static lib), specifically so the result can
be loaded into Ghidra (with its matching .pdb) to get real, named decompiled v56-era
engine code - mirroring what was already done for the v134 SDK (see
WwiseIntercept/Tools/generate_exports.py), just far less targeted since there's no
specific target .exe's export table to intersect against here.

Usage: python generate_v56_def.py <dumpbin.exe path> <output .def path> <lib1> [lib2 ...]
"""
import re
import subprocess
import sys

SYMBOL_LINE = re.compile(r"^\s+[0-9A-Fa-f]{4,16}\s+(\S+)\s*$")

def extract_symbols(dumpbin: str, lib_path: str) -> set[str]:
    result = subprocess.run([dumpbin, "/linkermember:1", lib_path], capture_output=True, text=True, check=True)
    symbols: set[str] = set()
    in_public = False
    for line in result.stdout.splitlines():
        if "public symbols" in line:
            in_public = True
            continue
        if line.strip() == "Summary":
            in_public = False
            continue
        if not in_public:
            continue
        m = SYMBOL_LINE.match(line)
        if not m:
            continue
        name = m.group(1)
        # Skip string-literal / RTTI-descriptor data symbols (??_C@ = string constant,
        # ??_R = RTTI descriptor) - not real code, and some choke the linker as function
        # exports since they're plain data without the DATA keyword.
        if name.startswith("??_C@") or name.startswith("??_R"):
            continue
        # A handful of entries come through as bare operator tokens ("==", "!=") - dumpbin
        # rendering artifacts, not resolvable link symbols. Real symbols always start with a
        # mangled-name lead-in (?, _, .) or a plain identifier character.
        if not re.match(r"^[A-Za-z_.?@$]", name):
            continue
        symbols.add(name)
    return symbols

def main() -> int:
    if len(sys.argv) < 4:
        print("Usage: generate_v56_def.py <dumpbin.exe> <output.def> <lib1> [lib2 ...]")
        return 1

    dumpbin, out_def, *libs = sys.argv[1:]
    all_symbols: set[str] = set()
    for lib in libs:
        syms = extract_symbols(dumpbin, lib)
        print(f"  {lib}: {len(syms)} public symbol(s)")
        all_symbols |= syms

    print(f"Total unique symbols: {len(all_symbols)}")

    with open(out_def, "w", encoding="utf-8") as f:
        f.write("; Auto-generated by generate_v56_def.py - do not hand-edit.\n")
        f.write("EXPORTS\n")
        for name in sorted(all_symbols):
            f.write(f"    {name}\n")

    print(f"Wrote {out_def}")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
